#!/usr/bin/env python3
"""Build Hiško's knowledge base for /api/aktiva.

Sources (aktiva-ai/kb/ and the pages):
  concept.md        what the concept is, the demo data, the pilot
  zakonodaja.md     Slovenian building-management law (SZ-1, SPZ, rules), with articles
  aktiva.md         public facts about Aktiva upravljanje and the group
  governance.md     AI Act, GDPR, safe rollout, metrics, opportunity list
  priloznosti.html, odgovorno.html, upravnik.html   the text of the pages, so Hiško can talk about them
  /projects/experience.json, /projects.json   the author's public CV and projects (shared with Solis DIY's builder)

Output: repo-root/api/_aktiva_kb.js (export default "<markdown>").
Run: python aktiva-ai/kb/build.py   (no dependencies)
"""
import importlib.util
import json
from pathlib import Path

KB = Path(__file__).resolve().parent
SITE = KB.parent
ROOT = SITE.parent

# PageText and author_md live in the Solis DIY builder; reuse them rather than keep two copies.
_spec = importlib.util.spec_from_file_location("solis_build", ROOT / "solis-diy" / "kb" / "build.py")
solis = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(solis)

MADE = ("Rok read Aktiva's public pages and the Slovenian building-management law (SZ-1, SPZ and the rules on the reserve fund and heating costs), "
        "built Hiško on that knowledge base with a work-order format the upravnik can confirm, the upravnik's view with the metrics a pilot would track, "
        "an opportunity map of AI use cases across security, cleaning and building management, and a page on responsible use under the AI Act and GDPR. "
        "He used AI throughout, for research, code and the assistant itself.")


def page_md(name, title):
    p = solis.PageText()
    p.feed((SITE / name).read_text(encoding="utf-8"))
    return f"# PAGE {name}: {title}\n\nText as shown on the page. Parts drawn by scripts are summarised elsewhere in this knowledge base.\n\n{p.text()}"


def demo_md():
    d = json.loads((SITE / "assets" / "demo.json").read_text(encoding="utf-8"))
    s = d["sim"]
    out = ["# DEMO DATA (fictional) used on the pages",
           f"- Fictional building {d['building']['name']}, {d['building']['address']}, {d['building']['units']} apartments; the owner's cost statement on index.html is sent as PAGE CONTEXT.",
           f"- Upravnik view (upravnik.html) shows a SIMULATION, not measurements: {s['period']}: {s['questions']} questions, {s['selfServed']:.0%} solved without the upravnik, "
           f"{s['orders']} work orders, {s['escalated']:.0%} handed to a person, first answer {s['firstResponse']} (before: {s['before']}), {s['hoursSaved']} hours saved a month, "
           f"accuracy on the evaluation set {s['accuracy']:.0%}, satisfaction {s['csat']}/5.",
           "- Topics: " + ", ".join(f"{t} {v:.0%}" for t, v in s["topics"]) + ".",
           "- Languages: " + ", ".join(f"{t} {v:.0%}" for t, v in s["languages"]) + ".",
           "- Always call these numbers a simulation; real baselines would be collected in the first two weeks of a pilot."]
    return "\n".join(out)


def main():
    parts = [
        (KB / "concept.md").read_text(encoding="utf-8"),
        demo_md(),
        page_md("priloznosti.html", "Opportunity map (\"Zakaj ta koncept\")"),
        page_md("odgovorno.html", "Responsible use of AI"),
        page_md("upravnik.html", "The upravnik's view"),
        solis.author_md(exclude=("solis-diy",), made=MADE),
        "# LAW\n\n" + (KB / "zakonodaja.md").read_text(encoding="utf-8"),
        "# AKTIVA\n\n" + (KB / "aktiva.md").read_text(encoding="utf-8"),
        "# GOVERNANCE\n\n" + (KB / "governance.md").read_text(encoding="utf-8"),
    ]
    text = "\n\n---\n\n".join(s.strip() for s in parts) + "\n"
    out = ROOT / "api" / "_aktiva_kb.js"
    out.write_text("// Generated by aktiva-ai/kb/build.py. Do not edit by hand.\nexport default " + json.dumps(text, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(text):,} characters")


if __name__ == "__main__":
    main()
