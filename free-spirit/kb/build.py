#!/usr/bin/env python3
"""Build Ogledalo's knowledge base for /api/freespirit.

Sources (free-spirit/kb/ and the pages):
  anja.md, koncept.md   who Anja is, her offer, this concept
  teme-*.md             her 121 public articles, summarised by topic in our own words
  ../assets/articles.json   title, link, theme and date of every article
  /projects/experience.json, /projects.json   the author's public CV (shared with Solis DIY's builder)

The "Opombe za urednika" section of each teme-*.md stays out of the bot's base.

Output: repo-root/api/_freespirit_kb.js (export default "<markdown>").
Run: python free-spirit/kb/build.py   (no dependencies)
"""
import importlib.util
import json
import re
from pathlib import Path

KB = Path(__file__).resolve().parent
SITE = KB.parent
ROOT = SITE.parent

# author_md lives in the Solis DIY builder; reuse it rather than keep two copies.
_spec = importlib.util.spec_from_file_location("solis_build", ROOT / "solis-diy" / "kb" / "build.py")
solis = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(solis)

MADE = ("Rok went through Anja's public site and her 121 articles with the help of AI, summarised them by topic in new words, "
        "redesigned the page around the person who arrives rather than the newest post, and built Ogledalo so that it asks more than it tells, "
        "as Anja does. He used AI throughout, for research, code and the assistant itself.")

THEMES = {"sebe": "Kdo sem danes", "izgorelost": "Izgorelost in energija", "strah": "Strah in kriza", "prehod": "Sprememba in prehod",
          "meje": "Meje in vzorci", "denar": "Denar in vrednost", "sluzba": "Iskanje službe"}


def topics():
    out = []
    for f in sorted(KB.glob("teme-*.md")):
        text = f.read_text(encoding="utf-8")
        out.append(re.split(r"\n## Opombe za urednika", text)[0].strip())
    return out


def articles_md():
    arts = json.loads((SITE / "assets" / "articles.json").read_text(encoding="utf-8"))
    out = ["# VSI ČLANKI (povezave piši točno tako)"]
    for key, name in THEMES.items():
        out += ["", f"## {name}"]
        for a in arts:
            if a["th"] == key:
                out.append(f"- [{a['t']}](https://kariera.freespirithc.com/{a['u']}/)")
    return "\n".join(out)


def main():
    parts = [
        (KB / "anja.md").read_text(encoding="utf-8"),
        (KB / "koncept.md").read_text(encoding="utf-8"),
        *topics(),
        articles_md(),
        solis.author_md(exclude=("aktiva-ai", "solis-diy", "free-spirit"), made=MADE),
    ]
    text = "\n\n---\n\n".join(s.strip() for s in parts) + "\n"
    out = ROOT / "api" / "_freespirit_kb.js"
    out.write_text("// Generated by free-spirit/kb/build.py. Do not edit by hand.\nexport default " + json.dumps(text, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(text):,} characters")


if __name__ == "__main__":
    main()
