// Generates the 1,000 page shells (trades/<trade>/NN-slug.html) and trades/sites.js (catalogue for the indexes).
// Usage: node tools/gen.js   (run from trades/)
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
global.window = {};
new Function(fs.readFileSync(path.join(ROOT, 'engine.js'), 'utf8'))();
const T = window.T;
for (const id of T.ORDER) new Function('T', fs.readFileSync(path.join(ROOT, 'data', id + '.js'), 'utf8'))(T);
const attr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const cat = [];
let pages = 0;
for (const id of T.ORDER) {
  const D = T.TR[id], dir = path.join(ROOT, id);
  fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) if (/^\d\d-.*\.html$/.test(f)) fs.unlinkSync(path.join(dir, f));
  const used = new Set();
  for (let n = 1; n <= 40; n++) {
    let salt = 0, B;
    do { B = T.biz(id, n, salt++); } while (used.has(B.name.toLowerCase()) && salt < 50);
    used.add(B.name.toLowerCase());
    const html = `<!DOCTYPE html>
<html lang="en-GB">
<head>
<meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${attr(B.title)}</title>
<meta name="description" content="${attr(B.desc)}">
<script>try{if(self!==parent||location.hash=='#t')document.documentElement.classList.add('embed')}catch(e){document.documentElement.classList.add('embed')}</script>
<script src="../pics.js"></script><script src="../engine.js"></script><script src="../data/${id}.js"></script>
</head>
<body><script>P.base='../';T.site('${id}',${n},${B.salt})</script></body>
</html>
`;
    fs.writeFileSync(path.join(dir, B.file), html);
    const th = T.THEMES[B.theme];
    cat.push([id, n, B.file, B.name, B.town, B.region, B.cc, B.theme, B.rating, B.nrev, B.years, B.owner.first + ' ' + B.owner.sur, B.headline]);
    pages++;
  }
}
const trades = T.ORDER.map(id => { const D = T.TR[id]; return [id, D.name, D.plural, D.icon, D.emergency ? 1 : 0, D.noun]; });
const themes = T.THEMES.map(t => [t.name, t.hf, t.bf, t.acc, t.bg, t.ink, t.dark, t.hero]);
fs.writeFileSync(path.join(ROOT, 'sites.js'), '/* generated by tools/gen.js */\nwindow.SITES=' + JSON.stringify({ trades, themes, sites: cat }) + ';\n');

// index pages: hub + one per trade
const idx = (title, desc, pre, trade) => `<!DOCTYPE html>
<html lang="en-GB">
<head>
<meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${attr(title)}</title>
<meta name="description" content="${attr(desc)}">
<link rel="preconnect" href="https://fonts.googleapis.com"><link href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,400..800&family=JetBrains+Mono:wght@500&display=swap" rel="stylesheet">
</head>
<body${trade ? ` data-trade="${trade}"` : ''}>
<script src="${pre}sites.js"></script><script src="${pre}engine.js"></script><script src="${pre}hub.js"></script>
</body>
</html>
`;
fs.writeFileSync(path.join(ROOT, 'index.html'), idx('1,000 Trade Websites', 'Forty complete website designs for each of 25 trades: plumbers, electricians, tilers, roofers and more.', '', ''));
for (const id of T.ORDER) { const D = T.TR[id]; fs.writeFileSync(path.join(ROOT, id, 'index.html'), idx(`40 ${D.plural} Websites`, `Forty complete website designs for ${D.plural.toLowerCase()}: prices, instant estimate, reviews and booking.`, '../', id)); }
console.log(pages, 'pages + 26 indexes');
